const fs = require("fs");
const path = require("path");

/**
 * Generate src/registry.ts with lazy imports of local icon JSON files.
 *
 * Reads icon names from a source folder, strips .json extensions, and
 * creates registry entries that load the matching bundled JSON file.
 *
 * Usage:
 *   node scripts/generate-registry.js <source-folder>
 *
 * The source folder should contain .json files whose names are the icon IDs.
 *
 * Example:
 *   node scripts/generate-registry.js ./src/icons
 */

const sourceArg = process.argv[2];
if (!sourceArg) {
  console.error("Usage: node scripts/generate-registry.js <source-folder>");
  console.error("  e.g. node scripts/generate-registry.js D:/Downloads/Iconaassets/public/icons");
  process.exit(1);
}
const sourceFolder = path.resolve(sourceArg);

// ── Read icon names ──────────────────────────────────────────────
let files;
try {
  files = fs.readdirSync(sourceFolder).filter((f) => f.endsWith(".json")).sort();
} catch (err) {
  console.error(`Cannot read folder: ${sourceFolder}`);
  console.error(err.message);
  process.exit(1);
}

if (files.length === 0) {
  console.error(`No .json files found in ${sourceFolder}`);
  process.exit(1);
}

// Strip all trailing .json suffixes
function cleanName(filename) {
  let name = filename;
  while (name.endsWith(".json")) name = name.slice(0, -5);
  return name;
}

const names = files.map(cleanName).filter(Boolean);

// ── Write registry.ts ────────────────────────────────────────────
const ids = `export const iconIds = [\n${names
  .map((name) => `  ${JSON.stringify(name)},`)
  .join("\n")}\n] as const;\nexport type IconId = (typeof iconIds)[number];\n\n`;
const entries = names
  .map(
    (name) =>
      `  ${JSON.stringify(name)}: () => import(${JSON.stringify(`./icons/${name}.json`)}),`
  )
  .join("\n");

const content = [
  "// Auto-generated by scripts/generate-registry.js",
  "// Icon data is bundled locally; no runtime network requests are made.",
  ids,
  `export const registry: Record<IconId, () => Promise<unknown>> = {`,
  entries,
  "};",
  "",
].join("\n");

const registryPath = path.resolve(__dirname, "../src/registry.ts");
fs.writeFileSync(registryPath, content, "utf-8");
fs.writeFileSync(path.resolve(__dirname, "icon-names.json"), JSON.stringify(names, null, 2) + "\n", "utf-8");

const entryDir = path.resolve(__dirname, "../src/icon-entries");
fs.mkdirSync(entryDir, { recursive: true });
const wantedEntries = new Set(names.map((name) => `${name}.tsx`));
for (const file of fs.readdirSync(entryDir)) {
  if (file.endsWith(".tsx") && !wantedEntries.has(file)) fs.unlinkSync(path.join(entryDir, file));
}
for (const name of names) {
  const entry = [
    `import React from "react";`,
    `import IconRenderer from "../IconRenderer";`,
    `import animationData from ${JSON.stringify(`../icons/${name}.json`)};`,
    `import type { IconRendererProps } from "../IconRenderer";`,
    "",
    `const loadAnimation = () => Promise.resolve(animationData);`,
    `type IconProps = Omit<IconRendererProps, "id" | "loadAnimation">;`,
    "",
    `export default function IconEntry(props: IconProps) {`,
    `  return <IconRenderer id=${JSON.stringify(name)} loadAnimation={loadAnimation} {...props} />;`,
    `}`,
    "",
  ].join("\n");
  fs.writeFileSync(path.join(entryDir, `${name}.tsx`), entry, "utf-8");
}

console.log(`\n✓ Registry generated at src/registry.ts`);
console.log(`  ${names.length} icons — generic registry plus tree-shakeable subpath entries`);
